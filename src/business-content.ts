type Evidence = keyof typeof businessSources;
function scenario(
  unitId: UnitId,
  code: string,
  sourceId: Evidence,
  citation: string,
  prompt: string,
  correct: string,
  wrong: [string, string, string],
  explanation: string,
  actionSteps: [string, string, string?],
): Question {
  const index = Number(code.split("-").at(-1));
  const stage: Question["stage"] =
    unitId === "common-contract"
      ? "계약·사업관리"
      : unitId === "common-process"
        ? index === 2 || index === 10
          ? "선행연구"
          : index <= 9
            ? "소요·전략"
            : "계약·사업관리"
        : unitId === "common-management"
          ? index <= 6 || index === 19
            ? "계약·사업관리"
            : index === 17
              ? "계약·사업관리"
              : [7, 8, 9, 10, 13, 14, 15, 16].includes(index)
                ? "운용·지원"
                : "시험평가·인도"
          : "소요·전략";
  return {
    id: `q-business-${code}`,
    unitId,
    concept: `business-${code}`,
    topic: "실무·상황",
    stage,
    prompt,
    options: [correct, ...wrong],
    answerIndex: 0,
    explanation,
    sourceId,
    citation,
    actionSteps: actionSteps.filter((s): s is string => !!s),
    scenario: true,
    status: "published",
    evidenceCheckedAt: "2026-10-25",
  };
}
